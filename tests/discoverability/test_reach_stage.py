    # -------------------------------------------------------------
    # 4. Robots.txt Parser, Semantics, & AI Bot Checks
    # -------------------------------------------------------------
    def test_robots_wildcard_allow_and_disallow(self):
        """Verify robots parser handles wildcard allow vs disallow."""
        report = RobotsInspector.parse("https://example.com/robots.txt", 200, "User-agent: *\nDisallow: /")
        allowed, group, rule = report.evaluate_bot("GPTBot", "/")
        self.assertFalse(allowed)

        report_allow = RobotsInspector.parse("https://example.com/robots.txt", 200, "User-agent: *\nAllow: /")
        allowed_w, _, _ = report_allow.evaluate_bot("GPTBot", "/")
        self.assertTrue(allowed_w)

    def test_robots_ai_specific_disallow(self):
        """Verify specific AI bot disallow overrides wildcard allow."""
        text = """
        User-agent: *
        Allow: /

        User-agent: GPTBot
        User-agent: ClaudeBot
        Disallow: /
        """
        report = RobotsInspector.parse("https://example.com/robots.txt", 200, text)

        # GPTBot and ClaudeBot are disallowed
        allowed_gpt, group_gpt, _ = report.evaluate_bot("GPTBot", "/")
        self.assertFalse(allowed_gpt)

        allowed_claude, group_claude, _ = report.evaluate_bot("ClaudeBot", "/")
        self.assertFalse(allowed_claude)

        # PerplexityBot falls back to wildcard (allowed)
        allowed_perp, group_perp, _ = report.evaluate_bot("PerplexityBot", "/")
        self.assertTrue(allowed_perp)

    def test_robots_allow_overriding_disallow_path_specificity(self):
        """Verify Allow directive overrides Disallow according to path specificity."""
        # Disallow: / but Allow: /public/
        text = """
        User-agent: *
        Disallow: /
        Allow: /public/
        """
        report = RobotsInspector.parse("https://example.com/robots.txt", 200, text)

        # Root is disallowed
        allowed_root, _, _ = report.evaluate_bot("GPTBot", "/")
        self.assertFalse(allowed_root)

        # /public/page is allowed
        allowed_pub, _, rule = report.evaluate_bot("GPTBot", "/public/page")
        self.assertTrue(allowed_pub)
        self.assertEqual(rule.rule_type, "allow")

    def test_robots_equal_length_allow_precedence(self):
        """Verify when Allow and Disallow have equal length, Allow takes precedence."""
        text = """
        User-agent: *
        Disallow: /page
        Allow: /page
        """
        report = RobotsInspector.parse("https://example.com/robots.txt", 200, text)
        allowed, _, rule = report.evaluate_bot("GPTBot", "/page")
        self.assertTrue(allowed)
        self.assertEqual(rule.rule_type, "allow")


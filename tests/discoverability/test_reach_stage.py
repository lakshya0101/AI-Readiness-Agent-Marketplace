def _mock_http_response(
    url: str,
    status_code: int = 200,
    body: bytes = b"",
    headers: dict = None,
    redirect_chain: list = None,
    error: str = None,
) -> HttpResponse:
    return HttpResponse(
        requested_url=url,
        final_url=url,
        status_code=status_code,
        redirect_chain=redirect_chain or [],
        headers=headers or {"content-type": "text/html; charset=utf-8"},
        body=body,
        error=error,
    )


